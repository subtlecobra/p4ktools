#!/usr/bin/env python3
"""Generates crates/formats/src/spirv/table.rs from the Khronos SPIR-V grammar (MIT).

Usage: tools/gen_spirv_table.py <SPIRV-Headers>/include/spirv/unified1 > crates/formats/src/spirv/table.rs
Only needed to move to a newer grammar: the generated file is committed.
"""
import json
import os
import sys


def rs(s):
    return json.dumps(s)


def operands(ops):
    q = {None: 0, "?": 1, "*": 2}
    return "&[" + ", ".join("(%s, %d)" % (rs(o["kind"]), q[o.get("quantifier")]) for o in ops) + "]"


def main():
    d = sys.argv[1]
    core = json.load(open(os.path.join(d, "spirv.core.grammar.json")))
    glsl = json.load(open(os.path.join(d, "extinst.glsl.std.450.grammar.json")))
    print("//! GENERATED by tools/gen_spirv_table.py from the Khronos grammar %d.%d rev %d (MIT licence); do not edit."
          % (core["major_version"], core["minor_version"], core["revision"]))
    print()
    print("/// (operand kind, quantifier: 0 one, 1 optional, 2 any number)\npub type Operand = (&'static str, u8);")
    print("pub struct Inst {\n    pub op: u16,\n    pub name: &'static str,\n    pub operands: &'static [Operand],\n}")
    print("pub struct Enumerant {\n    pub value: u32,\n    pub name: &'static str,\n    pub params: &'static [Operand],\n}")
    print("pub struct EnumKind {\n    pub kind: &'static str,\n    pub bits: bool,\n    pub values: &'static [Enumerant],\n}")
    print()
    print("/// Sorted by opcode (first spelling of an aliased opcode).\npub const INSTS: &[Inst] = &[")
    seen = {}
    for i in core["instructions"]:
        seen.setdefault(i["opcode"], i)
    for op in sorted(seen):
        i = seen[op]
        print("    Inst { op: %d, name: %s, operands: %s }," % (op, rs(i["opname"]), operands(i.get("operands", []))))
    print("];\n")
    print("pub const ENUMS: &[EnumKind] = &[")
    for k in core["operand_kinds"]:
        if k["category"] not in ("BitEnum", "ValueEnum"):
            continue
        print("    EnumKind { kind: %s, bits: %s, values: &[" % (rs(k["kind"]), "true" if k["category"] == "BitEnum" else "false"))
        vals = {}
        for e in k["enumerants"]:
            v = e["value"]
            v = int(v, 16) if isinstance(v, str) else v
            vals.setdefault(v, e)
        for v in sorted(vals):
            e = vals[v]
            print("        Enumerant { value: %d, name: %s, params: %s }," % (v, rs(e["enumerant"]), operands(e.get("parameters", []))))
        print("    ] },")
    print("];\n")
    print("/// GLSL.std.450 extended instructions, sorted by number.\npub const GLSL_STD_450: &[(u32, &str)] = &[")
    for i in sorted(glsl["instructions"], key=lambda x: x["opcode"]):
        print("    (%d, %s)," % (i["opcode"], rs(i["opname"])))
    print("];")


main()
